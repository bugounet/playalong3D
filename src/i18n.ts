export const catalogs: Record<Language, Record<string, string>> = {
  fr,
  en,
  de,
  es,
};

export function getInitialLanguage(): Language {
  const stored = window.localStorage.getItem("playalong3d-language");
  if (stored === "fr" || stored === "en" || stored === "de" || stored === "es") {
    return stored;
  }
  const browserLanguage = navigator.language.toLowerCase().slice(0, 2);
  return browserLanguage === "fr" ||
    browserLanguage === "de" ||
    browserLanguage === "es"
    ? browserLanguage
    : "en";
}

export function translate(
  language: Language,
  key: string,
  variables: Record<string, string | number> = {},
) {
  const template = catalogs[language][key] ?? en[key] ?? fr[key] ?? key;
  return Object.entries(variables).reduce(
    (result, [name, value]) =>
      result.replaceAll(`{${name}}`, String(value)),
    template,
  );
}
